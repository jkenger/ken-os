import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import { parseBaseline, parseLabMeta, parseProbeQuestions, parseTopicMap, type LabDefinition } from "@ken-os/domain";

// Turns content/engineering-lab and labs/ into checked TypeScript, so the hosted app never reads repo files at runtime.
const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDirectory, "../../..");
const outDir = resolve(scriptDirectory, "../src/features/engineering-lab/generated");
const mode = process.argv[2];
if (mode !== "--write" && mode !== "--check") throw new Error("Use --write to regenerate or --check to verify generated lab content.");

const read = (...parts: string[]) => readFileSync(resolve(repoRoot, ...parts), "utf8").replace(/\r\n/g, "\n");

const labs: LabDefinition[] = [];
const solutions: Record<string, string> = {};
for (const folder of readdirSync(resolve(repoRoot, "labs"), { withFileTypes: true }).filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort()) {
  const { probeId, ...meta } = parseLabMeta(parse(read("labs", folder, "lab.yaml")), folder);
  const readme = read("labs", folder, "README.md").trim();
  if (meta.runner === "probe") {
    labs.push({ ...meta, readme, starter: "", tests: "", setup: "", probe: { id: probeId!, questions: parseProbeQuestions(parse(read("labs", folder, "questions.yaml")), folder) } });
    continue;
  }
  labs.push({
    ...meta,
    readme,
    starter: read("labs", folder, "starter", "main.js"),
    tests: read("labs", folder, "tests", "main.test.js"),
    setup: meta.runner === "pglite" ? read("labs", folder, "setup.sql") : "",
    probe: null,
  });
  solutions[folder] = read("labs", folder, "solution", "main.js");
}

const topicMap = parseTopicMap(parse(read("content/engineering-lab/curriculum/topics.yaml")), new Map(labs.map((lab) => [lab.id, lab.modes])));
for (const lab of labs) {
  for (const topicId of lab.topics) {
    const topic = topicMap.topics.find((item) => item.id === topicId);
    if (!topic) throw new Error(`labs/${lab.id}: unknown topic ${topicId}`);
  }
}
const baseline = parseBaseline(parse(read("content/engineering-lab/learner/baseline.yaml")), topicMap);

const header = "// Generated by scripts/generate-lab-content.ts from content/engineering-lab and labs/. Do not edit.\n";
const outputs = new Map<string, string>([
  [resolve(outDir, "curriculum.generated.ts"), `${header}import type { Baseline, LabDefinition, TopicMap } from "@ken-os/domain";

export const topicMap: TopicMap = ${JSON.stringify(topicMap, null, 2)};

export const baseline: Baseline = ${JSON.stringify(baseline, null, 2)};

export const labs: LabDefinition[] = ${JSON.stringify(labs, null, 2)};
`],
  [resolve(outDir, "lab-solutions.generated.ts"), `${header}// Server only: never import this from a client component.
export const labSolutions: Record<string, string> = ${JSON.stringify(solutions, null, 2)};
`],
]);

let stale = false;
mkdirSync(outDir, { recursive: true });
for (const [path, content] of outputs) {
  if (mode === "--write") {
    writeFileSync(path, content, "utf8");
    continue;
  }
  let actual = "";
  try { actual = readFileSync(path, "utf8").replace(/\r\n/g, "\n"); } catch { /* missing output */ }
  if (actual !== content) {
    stale = true;
    console.error(`Generated lab content is stale: ${path}. Run pnpm --filter @ken-os/web lab:generate.`);
  }
}
if (stale) process.exitCode = 1;
else console.log(mode === "--write" ? `Lab content generated: ${topicMap.topics.length} topics, ${labs.length} labs.` : "Lab content is current.");
